"""Request and response models for the HTTP API.

Inputs forbid unknown fields and bound every string. Responses are built from
service records with ``from_attributes`` so the wire shape is defined here, in
one place, and exported to TypeScript by ``npm run contracts``.
"""

from __future__ import annotations

from datetime import datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

CourseOrigin = Literal["sample", "topic", "materials"]
SourceKind = Literal["pdf", "docx", "markdown", "text", "authored"]
SourceStatus = Literal["extracted", "needs_attention"]
SectionKind = Literal["document", "page", "heading"]
JobStatus = Literal["queued", "running", "succeeded", "failed", "cancelled"]

ConceptOrigin = Literal["learner", "outline", "model", "sample"]
ConceptTag = Literal["conceptual", "calculation", "visual", "procedural"]
MasteryStateName = Literal["not_assessed", "building", "needs_evidence", "demonstrated"]
SelfReportLevel = Literal["new", "some", "confident"]
PaceName = Literal["relaxed", "standard", "brisk"]
DensityName = Literal["concise", "balanced", "detailed"]

Title = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=200)]
LongText = Annotated[str, StringConstraints(strip_whitespace=True, max_length=4000)]
Statement = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=400)]
Reason = Annotated[str, StringConstraints(strip_whitespace=True, max_length=500)]
#: An identifier as generated by ``infrastructure.ids.new_id``.
Identifier = Annotated[str, StringConstraints(pattern=r"^[a-z]{2,5}_[0-9a-f]{20}$")]


class _Input(BaseModel):
    model_config = ConfigDict(extra="forbid")


class _Output(BaseModel):
    model_config = ConfigDict(from_attributes=True)


# -- courses ---------------------------------------------------------------


class CourseCreate(_Input):
    title: Title
    description: LongText = ""
    #: A learner creates a course from a topic or from materials. Sample courses are built in.
    origin: Literal["topic", "materials"]
    topic: LongText | None = None


class CourseUpdate(_Input):
    title: Title | None = None
    description: LongText | None = None


class Course(_Output):
    id: str
    title: str
    description: str
    origin: CourseOrigin
    topic: str | None
    source_count: int
    created_at: datetime
    updated_at: datetime
    last_opened_at: datetime | None


class CourseList(_Output):
    courses: list[Course]


# -- sources ---------------------------------------------------------------


class Source(_Output):
    id: str
    course_id: str
    display_name: str
    kind: SourceKind
    status: SourceStatus
    #: Learner-readable notes about anything extraction may have missed.
    warnings: list[str]
    size_bytes: int
    char_count: int
    section_count: int
    chunk_count: int
    #: Number of pages with extracted text, for paged documents; otherwise 0.
    page_count: int
    created_at: datetime


class SourceList(_Output):
    sources: list[Source]


class SourceSection(_Output):
    id: str
    ordinal: int
    kind: SectionKind
    title: str | None
    page_number: int | None
    level: int | None
    char_count: int
    #: 0–1: how far the extracted text of this section can be trusted.
    confidence: float


class SourceDetail(_Output):
    source: Source
    sections: list[SourceSection]


class ImportRequest(_Input):
    """Absolute paths chosen by the learner. Only the desktop shell may send this."""

    paths: list[Annotated[str, StringConstraints(min_length=1, max_length=4096)]] = Field(
        min_length=1, max_length=50
    )


class HighlightSegment(_Output):
    text: str
    highlighted: bool


class SearchHit(_Output):
    chunk_id: int
    source_id: str
    source_name: str
    section_title: str | None
    page_number: int | None
    #: The matching passage, split so matched words can be emphasised without markup.
    excerpt: list[HighlightSegment]


class SearchResults(_Output):
    query: str
    hits: list[SearchHit]


# -- curriculum ------------------------------------------------------------


class Objective(_Output):
    id: str
    statement: str


class Prerequisite(_Output):
    concept_id: str
    title: str
    #: Why it is needed first. Empty when nobody has said.
    reason: str


class SourceRef(_Output):
    id: int
    source_id: str
    source_name: str
    section_id: str
    section_title: str | None
    page_number: int | None


class Knowledge(_Output):
    """What the evidence says about the learner and one concept. Deliberately no score."""

    state: MasteryStateName
    label: str
    #: What is still needed before the concept counts as demonstrated.
    missing: list[str]
    answered: int
    self_report: SelfReportLevel | None
    review_due_at: datetime | None


class Concept(_Output):
    id: str
    course_id: str
    title: str
    summary: str
    position: int
    #: Expected lesson size: 1 short, 2 medium, 3 long.
    complexity: int
    tags: list[ConceptTag]
    origin: ConceptOrigin
    objectives: list[Objective]
    prerequisites: list[Prerequisite]
    source_refs: list[SourceRef]
    #: Depth in the map (0 needs nothing); null while the graph contains a loop.
    layer: int | None
    knowledge: Knowledge


class CurriculumIssue(_Output):
    code: str
    severity: Literal["error", "warning"]
    concept_ids: list[str]
    message: str


class Curriculum(_Output):
    course_id: str
    #: In the learner's own order.
    concepts: list[Concept]
    #: Concept ids in an order that respects every prerequisite; empty while there is a loop.
    learning_order: list[str]
    issues: list[CurriculumIssue]
    startable: bool


class ConceptCreate(_Input):
    title: Title
    summary: LongText = ""
    objectives: list[Statement] = Field(default_factory=list, max_length=12)


class ConceptUpdate(_Input):
    title: Title | None = None
    summary: LongText | None = None
    complexity: int | None = Field(default=None, ge=1, le=3)
    tags: list[ConceptTag] | None = Field(default=None, max_length=4)


class ConceptOrder(_Input):
    #: Every concept of the course, once, in the learner's preferred order.
    concept_ids: list[Identifier] = Field(max_length=200)


class ObjectiveInput(_Input):
    #: The id of an objective being kept or reworded; omitted for a new one.
    id: Identifier | None = None
    statement: Statement


class ObjectivesUpdate(_Input):
    objectives: list[ObjectiveInput] = Field(max_length=12)


class PrerequisiteInput(_Input):
    concept_id: Identifier
    reason: Reason = ""


class PrerequisitesUpdate(_Input):
    prerequisites: list[PrerequisiteInput] = Field(max_length=12)


class SourceRefCreate(_Input):
    section_id: Identifier


class OutlineCandidate(_Output):
    section_id: str
    title: str
    source_id: str
    source_name: str


class OutlineCandidates(_Output):
    candidates: list[OutlineCandidate]


class OutlineSelection(_Input):
    section_ids: list[Identifier] = Field(min_length=1, max_length=40)


class Passage(_Output):
    chunk_id: int
    source_id: str
    source_name: str
    section_id: str
    section_title: str | None
    page_number: int | None
    text: str


class Passages(_Output):
    passages: list[Passage]


# -- learner ---------------------------------------------------------------


class LearnerPreferences(_Output):
    pace: PaceName
    explanation_density: DensityName
    narration: bool
    captions: bool
    goal: str


class LearnerPreferencesUpdate(_Input):
    pace: PaceName | None = None
    explanation_density: DensityName | None = None
    narration: bool | None = None
    captions: bool | None = None
    goal: Annotated[str, StringConstraints(max_length=600)] | None = None


class SelfRating(_Input):
    level: SelfReportLevel


class ObservationSummary(_Output):
    id: int
    occurred_at: datetime
    kind: Literal["answer", "self_report"]
    state_before: MasteryStateName
    state_after: MasteryStateName
    #: What happened and what it means, in words for the learner.
    explanation: str


class ConceptEvidence(_Output):
    concept_id: str
    knowledge: Knowledge
    #: Newest first.
    history: list[ObservationSummary]


# -- jobs ------------------------------------------------------------------


class Job(_Output):
    id: str
    kind: str
    course_id: str | None
    status: JobStatus
    progress_done: int
    progress_total: int
    progress_message: str
    #: Present once the job has finished (or was cancelled part-way).
    result: Any | None
    error_code: str | None
    error_message: str | None
