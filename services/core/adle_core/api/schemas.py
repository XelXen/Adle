"""Request and response models for the HTTP API.

Inputs forbid unknown fields and bound every string. Responses are built from
service records with ``from_attributes`` so the wire shape is defined here, in
one place, and exported to TypeScript by ``npm run contracts``.
"""

from __future__ import annotations

from datetime import datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, StrictBool, StringConstraints

from adle_core.lessons import ir as lesson_ir
from adle_core.lessons.player import PlayerLesson, PlayerQuestion

CourseOrigin = Literal["sample", "topic", "materials"]
#: The kinds of subject a course may be (``lessons.axioms.SUBJECTS``; a test keeps them equal).
SubjectKey = Literal[
    "mathematics",
    "physics",
    "chemistry",
    "biology",
    "earth_science",
    "computer_science",
    "language",
    "literature",
    "history",
    "economics",
    "social_science",
    "arts",
    "general",
]
SourceKind = Literal["pdf", "docx", "markdown", "text", "authored"]
SourceStatus = Literal["extracted", "needs_attention"]
SectionKind = Literal["document", "page", "heading"]
JobStatus = Literal["queued", "running", "succeeded", "failed", "cancelled"]

ConceptOrigin = Literal["learner", "outline", "model", "sample"]
ConceptTag = Literal["conceptual", "calculation", "visual", "procedural"]
MasteryStateName = Literal["not_assessed", "building", "needs_evidence", "demonstrated"]
SelfReportLevel = Literal["new", "some", "confident"]
PaceName = Literal["relaxed", "standard", "brisk"]
DensityName = Literal["concise", "balanced", "detailed"]
LessonOrigin = Literal["sample", "generated"]
HypothesisStatus = Literal["tentative", "supported", "rejected", "resolved"]
StepKindName = Literal[
    "add_concepts",
    "resume_lesson",
    "revisit_prerequisite",
    "check",
    "another_explanation",
    "review",
    "practise",
    "start_lesson",
    "repeat_lesson",
    "create_lesson",
    "nothing_due",
]
PracticePurposeName = Literal["review", "check", "practise"]

Title = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=200)]
LongText = Annotated[str, StringConstraints(strip_whitespace=True, max_length=4000)]
Statement = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=400)]
Reason = Annotated[str, StringConstraints(strip_whitespace=True, max_length=500)]
#: An identifier as generated by ``infrastructure.ids.new_id``.
Identifier = Annotated[str, StringConstraints(pattern=r"^[a-z]{2,5}_[0-9a-f]{20}$")]


class _Input(BaseModel):
    model_config = ConfigDict(extra="forbid")


class _Output(BaseModel):
    model_config = ConfigDict(from_attributes=True)


# -- courses ---------------------------------------------------------------


class CourseCreate(_Input):
    #: Left out, Adle names the course (ADR-053).
    title: Title | None = None
    description: LongText = ""
    #: A learner creates a course from a topic or from materials. Sample courses are built in.
    origin: Literal["topic", "materials"]
    topic: LongText | None = None


class ProposalRequest(_Input):
    #: The learner asked Adle to set the course up: what is suggested is added, and the
    #: first lesson begun (ADR-053).
    setup: StrictBool = False


class CourseUpdate(_Input):
    title: Title | None = None
    description: LongText | None = None
    #: The kind of subject the course is, which then stands; or "auto": Adle decides.
    subject: SubjectKey | Literal["auto"] | None = None


class Course(_Output):
    id: str
    title: str
    description: str
    origin: CourseOrigin
    topic: str | None
    source_count: int
    concept_count: int
    created_at: datetime
    updated_at: datetime
    last_opened_at: datetime | None
    #: Its name was left to Adle, who names it from its files and its concepts (ADR-053).
    named_by_adle: bool = False
    #: The kind of subject it is, which decides how its lessons are formed (ADR-061).
    subject: SubjectKey = "general"
    #: Adle placed it; the learner has not chosen.
    subject_by_adle: bool = True
    #: It was brought in from a file: what it holds was made elsewhere (ADR-063).
    brought_in: bool = False


class CourseList(_Output):
    courses: list[Course]


class SubjectWay(_Output):
    """One kind of subject, and how a lesson of it goes."""

    key: SubjectKey
    name: str
    #: How a lesson of it goes, as short steps in order.
    steps: list[str]
    #: The ways of teaching that suit it.
    strategies: list[lesson_ir.Strategy]


class LessonRules(_Output):
    """How Adle forms a lesson (ADR-061): the rules of every lesson, in the order a lesson
    obeys them, and what each subject needs besides."""

    rules: list[str]
    subjects: list[SubjectWay]


# -- sources ---------------------------------------------------------------


class Source(_Output):
    id: str
    course_id: str
    display_name: str
    kind: SourceKind
    status: SourceStatus
    #: Learner-readable notes about anything extraction may have missed.
    warnings: list[str]
    size_bytes: int
    char_count: int
    section_count: int
    chunk_count: int
    #: Number of pages with extracted text, for paged documents; otherwise 0.
    page_count: int
    created_at: datetime
    #: Pages that are pictures, not read yet (ADR-060): they can be read with
    #: ``sources.read_pictures``, which sends each to the AI provider as a picture.
    picture_pages: list[int]


class SourceList(_Output):
    sources: list[Source]


class SourceSection(_Output):
    id: str
    ordinal: int
    kind: SectionKind
    title: str | None
    page_number: int | None
    level: int | None
    char_count: int
    #: 0–1: how far the extracted text of this section can be trusted.
    confidence: float


class SourceDetail(_Output):
    source: Source
    sections: list[SourceSection]


class ImportRequest(_Input):
    """Absolute paths chosen by the learner. Only the desktop shell may send this."""

    paths: list[Annotated[str, StringConstraints(min_length=1, max_length=4096)]] = Field(
        min_length=1, max_length=50
    )


class HighlightSegment(_Output):
    text: str
    highlighted: bool


class SearchHit(_Output):
    chunk_id: int
    source_id: str
    source_name: str
    section_title: str | None
    page_number: int | None
    #: The matching passage, split so matched words can be emphasised without markup.
    excerpt: list[HighlightSegment]


class SearchResults(_Output):
    query: str
    hits: list[SearchHit]


# -- curriculum ------------------------------------------------------------


class Objective(_Output):
    id: str
    statement: str


class Prerequisite(_Output):
    concept_id: str
    title: str
    #: Why it is needed first. Empty when nobody has said.
    reason: str


class SourceRef(_Output):
    id: int
    source_id: str
    source_name: str
    section_id: str
    section_title: str | None
    page_number: int | None


class Knowledge(_Output):
    """What the evidence says about the learner and one concept. Deliberately no score."""

    state: MasteryStateName
    label: str
    #: What is still needed before the concept counts as demonstrated.
    missing: list[str]
    answered: int
    self_report: SelfReportLevel | None
    review_due_at: datetime | None


class Concept(_Output):
    id: str
    course_id: str
    title: str
    summary: str
    position: int
    #: Expected lesson size: 1 short, 2 medium, 3 long.
    complexity: int
    tags: list[ConceptTag]
    origin: ConceptOrigin
    objectives: list[Objective]
    prerequisites: list[Prerequisite]
    source_refs: list[SourceRef]
    #: Depth in the map (0 needs nothing); null while the graph contains a loop.
    layer: int | None
    knowledge: Knowledge


class CurriculumIssue(_Output):
    code: str
    severity: Literal["error", "warning"]
    concept_ids: list[str]
    message: str


class Curriculum(_Output):
    course_id: str
    #: In the learner's own order.
    concepts: list[Concept]
    #: Concept ids in an order that respects every prerequisite; empty while there is a loop.
    learning_order: list[str]
    issues: list[CurriculumIssue]
    startable: bool


class ConceptCreate(_Input):
    title: Title
    summary: LongText = ""
    objectives: list[Statement] = Field(default_factory=list, max_length=12)


class ConceptUpdate(_Input):
    title: Title | None = None
    summary: LongText | None = None
    complexity: int | None = Field(default=None, ge=1, le=3)
    tags: list[ConceptTag] | None = Field(default=None, max_length=4)


class ConceptOrder(_Input):
    #: Every concept of the course, once, in the learner's preferred order.
    concept_ids: list[Identifier] = Field(max_length=200)


class ObjectiveInput(_Input):
    #: The id of an objective being kept or reworded; omitted for a new one.
    id: Identifier | None = None
    statement: Statement


class ObjectivesUpdate(_Input):
    objectives: list[ObjectiveInput] = Field(max_length=12)


class PrerequisiteInput(_Input):
    concept_id: Identifier
    reason: Reason = ""


class PrerequisitesUpdate(_Input):
    prerequisites: list[PrerequisiteInput] = Field(max_length=12)


class SourceRefCreate(_Input):
    section_id: Identifier


class OutlineCandidate(_Output):
    section_id: str
    title: str
    source_id: str
    source_name: str


class OutlineCandidates(_Output):
    candidates: list[OutlineCandidate]


class OutlineSelection(_Input):
    section_ids: list[Identifier] = Field(min_length=1, max_length=40)


class Passage(_Output):
    chunk_id: int
    source_id: str
    source_name: str
    section_id: str
    section_title: str | None
    page_number: int | None
    text: str


class Passages(_Output):
    passages: list[Passage]


# -- learner ---------------------------------------------------------------


class LearnerPreferences(_Output):
    pace: PaceName
    explanation_density: DensityName
    narration: bool
    captions: bool
    goal: str
    #: Empty when the learner has not chosen one.
    voice: str
    volume: int


class LearnerPreferencesUpdate(_Input):
    pace: PaceName | None = None
    explanation_density: DensityName | None = None
    narration: bool | None = None
    captions: bool | None = None
    goal: Annotated[str, StringConstraints(max_length=600)] | None = None
    voice: Annotated[str, StringConstraints(max_length=120)] | None = None
    volume: Annotated[int, Field(ge=0, le=100)] | None = None


class SelfRating(_Input):
    level: SelfReportLevel


class ObservationSummary(_Output):
    id: int
    occurred_at: datetime
    kind: Literal["answer", "self_report", "dismissal"]
    state_before: MasteryStateName
    state_after: MasteryStateName
    #: What happened and what it means, in words for the learner.
    explanation: str


class ConceptEvidence(_Output):
    concept_id: str
    knowledge: Knowledge
    #: Newest first.
    history: list[ObservationSummary]


# -- lessons ---------------------------------------------------------------


class LessonProgress(_Output):
    #: Index of the segment to resume at.
    position: int
    completed: bool
    #: False until the learner has opened the lesson at least once.
    started: bool


class LessonSummary(_Output):
    id: str
    course_id: str
    #: The concept the lesson is listed under.
    concept_id: str
    title: str
    #: Written by Adle (``sample``) or by the configured model (``generated``).
    origin: LessonOrigin
    estimated_minutes: int
    segment_count: int
    progress: LessonProgress
    #: Pictures the lesson is still waiting for. It can be taken meanwhile (ADR-031).
    pictures_pending: int = 0
    #: Its later parts are still being written. It can be taken meanwhile (ADR-048).
    writing: bool = False


class LessonList(_Output):
    lessons: list[LessonSummary]


class LessonAuthor(_Output):
    """Who wrote a lesson, by the names they went by when it was written."""

    provider: str
    models: list[str]
    #: A sentence saying that another model or provider stood in; empty when none did.
    note: str


class LessonForPlayer(_Output):
    """Everything the player needs: the validated lesson and the scenes it plays."""

    #: The lesson without its answer keys; answers are scored by the core.
    lesson: PlayerLesson
    scenes: list[lesson_ir.SceneArtifact]
    origin: LessonOrigin
    progress: LessonProgress
    #: Scenes that parts refer to and that are still being drawn. Each such part shows its
    #: picture in words until the picture arrives (ADR-031).
    pending_scene_ids: list[str] = Field(default_factory=list)
    #: Who wrote it, where a model did. Absent for the sample course, and for lessons
    #: written before this was kept.
    written_by: LessonAuthor | None = None
    #: The rest of the lesson is still being written. Its parts are added after these, and
    #: none of these changes (ADR-048).
    writing: bool = False
    #: The parts the learner said did not help and has not taken back (ADR-054).
    unhelpful_parts: list[str] = Field(default_factory=list)


class LessonProgressUpdate(_Input):
    position: int = Field(ge=0, le=100)
    completed: bool = False


# -- questions the learner asks in the middle of a lesson -----------------------


class AskRequest(_Input):
    """Something the learner wants to ask about one part of a lesson."""

    segment_id: Annotated[str, StringConstraints(pattern=r"^seg_[a-z0-9_]{1,40}$")]
    question: Annotated[str, StringConstraints(strip_whitespace=True, min_length=3, max_length=500)]
    #: Draw the part's picture again as the question says, rather than answer it in words
    #: (ADR-067).
    redraw: bool = False


class Author(_Output):
    provider: str
    model: str


class WrittenBy(_Output):
    """Who wrote something a model wrote."""

    provider: str = ""
    models: list[str] = Field(default_factory=list)
    #: Each provider and model that wrote part of it, in order.
    authors: list[Author] = Field(default_factory=list)
    #: A sentence to show when what wrote it was not what was asked first.
    note: str = ""


class AskCitation(_Output):
    source_name: str
    locator: str


class AskPicture(_Output):
    """The part's picture, drawn again because the learner asked (ADR-067)."""

    #: Offered beside the answer, or in use in the lesson in place of the part's own.
    state: Literal["offered", "in_use"]
    #: What it shows, in words.
    description: str


class Ask(_Output):
    """A question the learner asked about a part of a lesson, and the answer."""

    id: str
    lesson_id: str
    segment_id: str
    #: The learner's own words. Shown as plain text.
    question: str
    #: The answer. Display text: may contain $math$.
    paragraphs: list[str]
    citations: list[AskCitation]
    written_by: WrittenBy
    created_at: datetime
    #: The part's picture drawn again, when the learner asked for that.
    picture: AskPicture | None = None


class AskList(_Output):
    asks: list[Ask]
    #: How many a lesson keeps. Past this, one is removed before another is asked.
    limit: int


class AnswerRequest(_Input):
    """An answer to a question. Fill in the one field that matches the question's form."""

    #: The learner chose not to answer. Nothing else is read.
    skipped: bool = False
    option_id: Annotated[str, StringConstraints(max_length=16)] | None = None
    truth: bool | None = None
    number: float | None = Field(default=None, allow_inf_nan=False)
    text: Annotated[str, StringConstraints(max_length=400)] | None = None
    order: list[Annotated[str, StringConstraints(max_length=16)]] | None = Field(
        default=None, max_length=6
    )
    #: For an explanation: the rubric points the learner says their answer covered.
    covered: list[Annotated[str, StringConstraints(max_length=16)]] | None = Field(
        default=None, max_length=5
    )
    #: The learner asked for the hint before answering.
    hinted: bool = False
    #: The learner said they were not sure of this answer.
    unsure: bool = False


class AnswerResult(_Output):
    outcome: Literal["correct", "partial", "incorrect", "skipped"]
    #: About the answer that was given, when there is something specific to say.
    feedback: str | None
    #: Why the right answer is right.
    explanation: str
    correct_answer: str
    #: The right one among the options that were offered ("true" / "false" for a
    #: true-or-false question). Absent for a skipped question and for questions without options.
    correct_option: str | None
    #: What the answer changed about what Adle believes, in words.
    change: str
    knowledge: Knowledge
    attempt_number: int


# -- what next, progress, and practice ---------------------------------------


class NextStep(_Output):
    """Something worth doing now, with the reason for it. Never an instruction."""

    kind: StepKindName
    #: What the button says.
    title: str
    #: Why this step, in a sentence or two.
    reason: str
    concept_id: str | None
    lesson_id: str | None
    #: The kind of mistake a check is about, when it is about one.
    about: lesson_ir.MisconceptionKind | None
    #: The step needs the AI provider, and no key is set up.
    needs_key: bool


class LearningPlan(_Output):
    recommended: NextStep
    #: Other reasonable things to do instead, the most useful first.
    alternatives: list[NextStep]
    #: Something worth saying beside the suggestion (that stopping is fine, for one).
    note: str | None


class Hypothesis(_Output):
    """A possible explanation for a pattern of answers. A hypothesis, never a verdict."""

    kind: lesson_ir.MisconceptionKind
    status: HypothesisStatus
    #: Where it stands, in a sentence for the learner.
    description: str
    #: A slip of execution: noted, and never treated as a gap in understanding.
    is_slip: bool
    #: Still open, so the learner can say it does not describe them.
    can_dismiss: bool


class ConceptProgress(_Output):
    concept_id: str
    title: str
    knowledge: Knowledge
    lessons_total: int
    lessons_completed: int
    hypotheses: list[Hypothesis]
    #: Questions that could be asked now and would count as evidence.
    fresh_questions: int
    #: When a question that is being kept back becomes worth asking again.
    next_fresh_at: datetime | None
    review_due: bool


class ProgressSummary(_Output):
    """Counts of concepts by what the evidence says. Counts of states, never a score."""

    concepts: int
    demonstrated: int
    in_progress: int
    not_assessed: int
    reviews_due: int
    next_review_at: datetime | None


class SessionShown(_Output):
    concept_id: str
    title: str
    #: Right answers in the sitting. A count, not a rate: wrong answers are not in it.
    right: int
    #: Those of them that count in full: no hint, no "I am not sure", not marked by the
    #: learner themselves, not a repeat of a question just answered.
    right_unaided: int
    #: The concept counts as demonstrated now, by the usual criteria.
    demonstrated: bool


class SessionStillNeeded(_Output):
    concept_id: str
    title: str
    label: str
    missing: list[str]


class SessionReview(_Output):
    concept_id: str
    title: str
    due_at: datetime


class SessionSummary(_Output):
    """The latest sitting on a course and what it showed.

    A sitting is a run of activity with no long pause in it. Nobody starts or ends one;
    it is read off the record. Counts of answers and words for states: never a score.
    """

    started_at: datetime
    ended_at: datetime
    #: The learner may still be in it; otherwise it was "last time".
    current: bool
    lessons_completed: int
    answered: int
    shown: list[SessionShown]
    still_needed: list[SessionStillNeeded]
    reviews: list[SessionReview]


class LearningOverview(_Output):
    course_id: str
    plan: LearningPlan
    #: In an order that respects what each concept needs first.
    concepts: list[ConceptProgress]
    summary: ProgressSummary
    #: Null until something has been done on the course.
    session: SessionSummary | None


class PracticeRequest(_Input):
    #: The kind of mistake to check for first, when the learner came from a suggestion about one.
    about: lesson_ir.MisconceptionKind | None = None
    count: int = Field(default=3, ge=1, le=5)


class PracticeQuestion(_Output):
    #: The lesson the question belongs to. Answers go to ``lessons.answer`` with it.
    lesson_id: str
    question: PlayerQuestion


class PracticeSet(_Output):
    course_id: str
    concept_id: str
    concept_title: str
    purpose: PracticePurposeName
    #: Why these questions, or why there are none right now.
    reason: str
    questions: list[PracticeQuestion]
    #: When there will be something to ask, if nothing can be asked now.
    next_fresh_at: datetime | None


class UnhelpfulReport(_Input):
    """The learner says a part of a lesson did not help."""

    segment_id: Annotated[str, StringConstraints(pattern=r"^seg_[a-z0-9_]{1,40}$")]


# -- jobs ------------------------------------------------------------------


class JobProgressDetail(_Output):
    """What long work is doing just now, for a learner who is waiting for it.

    Nothing here is the answer itself: a stage, and the titles of what has been written.
    """

    #: ``waiting`` for a turn, ``thinking`` before the first word, ``writing``, ``drawing``
    #: a picture, or ``voicing``: the words are written, and the first part is still being
    #: recorded in the natural voice (ADR-051).
    stage: Literal["waiting", "thinking", "writing", "drawing", "voicing"] | None = None
    #: For something written part by part: the titles of the parts so far, in order (at
    #: most 40, each one line of at most 120 characters: ``generation.Outline``). The last
    #: one may still be being written.
    outline: list[str] = Field(default_factory=list)
    #: What is being written, as its own title, once that has arrived.
    title: str | None = None


class Job(_Output):
    id: str
    kind: str
    course_id: str | None
    #: What the job is about: a concept for a lesson, the course for a proposal.
    subject_id: str | None
    status: JobStatus
    progress_done: int
    progress_total: int
    progress_message: str
    #: What the work is doing just now, where it can say (see ``JobProgressDetail``).
    progress_detail: JobProgressDetail | None = None
    #: Present once the job has finished (or was cancelled part-way).
    result: Any | None
    error_code: str | None
    error_message: str | None
    #: When it was asked for.
    created_at: datetime | None = None


class JobList(_Output):
    jobs: list[Job]


class SceneTrial(_Output):
    """A picture to try in the player before a learner is shown it (ADR-038)."""

    id: str
    #: The scene class to run.
    scene_class: str
    #: The whole file, as it would be shown.
    source: str
    interactive: bool
    #: The names of the controls an interactive picture has.
    controls: list[str]
    #: A slide's steps (ADR-049): the trial goes through each. 0 for a picture that plays
    #: through.
    steps: int = 0


class SceneTrialList(_Output):
    trials: list[SceneTrial]


class SceneTrialReport(_Input):
    """How a trial went. ``passed``, or where it failed and what the player said."""

    #: True or false, and nothing that only reads as one.
    passed: StrictBool
    stage: Literal["boot", "compile", "runtime", "timeout", "unresponsive", "controls"] | None = (
        None
    )
    #: What the player said, cut short: it is told to the model that writes the file again.
    message: Annotated[str, StringConstraints(max_length=2000)] = ""


class LatestJob(_Output):
    #: Absent when there has never been one.
    job: Job | None


